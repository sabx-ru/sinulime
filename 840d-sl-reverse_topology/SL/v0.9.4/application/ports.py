from typing import Protocol, Mapping, Any

class SnapshotStore(Protocol):
    def get(self, snapshot_id: str) -> Mapping[str, Any]: ...
    def list(self, query: Mapping[str, Any], cursor: str | None, limit: int) -> Mapping[str, Any]: ...
    def prepare(self, snapshots: list[Mapping[str, Any]], generation: str | None = None) -> Any: ...
    def put(self, snapshot: Mapping[str, Any]) -> None: ...
    def publish(self, generation: str) -> None: ...

class EvidenceStore(Protocol):
    def get(self, evidence_id: str) -> Mapping[str, Any]: ...
    def put_batch(self, evidence: list[Mapping[str, Any]]) -> None: ...

class EventStore(Protocol):
    def list(self, query: Mapping[str, Any], cursor: str | None, limit: int) -> Mapping[str, Any]: ...
    def append_batch(self, events: list[Mapping[str, Any]], revision: int | None = None) -> list[Mapping[str, Any]]: ...
    def earliest_offset(self) -> int: ...
    def retain_through(self, offset: int) -> None: ...

class Resolver(Protocol):
    def resolve(self, artifact_id: str): ...
